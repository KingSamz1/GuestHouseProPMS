"""
PDF receipt generation for GuesthousePro — PostgreSQL version.
"""
import os
import re
from datetime import datetime
from utils.db import get_conn, get_account
from utils.pg import fetchone, execute, scalar

try:
    from reportlab.lib.pagesizes import A5
    from reportlab.lib.units import mm
    from reportlab.lib import colors
    from reportlab.pdfgen import canvas
    REPORTLAB_AVAILABLE = True
except ImportError:
    REPORTLAB_AVAILABLE = False

RECEIPTS_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "receipts"
)


def _ensure_dir():
    os.makedirs(RECEIPTS_DIR, exist_ok=True)


def _next_receipt_number():
    with get_conn() as conn:
        count = scalar(conn, "SELECT COUNT(*) FROM receipts") or 0
    seq  = count + 1
    year = datetime.now().strftime("%Y")
    return f"GHP-RCT-{year}-{seq:05d}"


def _safe_filename(name):
    name = re.sub(r'[\\/*?:"<>|]', "", name)
    return (name.strip().replace(" ", "_") or "receipt")


def generate_receipt(payment_id, display_name=None):
    from utils.logic import get_payment
    if not REPORTLAB_AVAILABLE:
        raise RuntimeError("PDF receipts need the 'reportlab' package.")

    _ensure_dir()
    payment = get_payment(payment_id)
    if not payment:
        raise ValueError("Payment not found")

    with get_conn() as conn:
        acc_row = fetchone(conn,
            "SELECT r.account_id FROM reservations r WHERE r.id=%s",
            (payment["reservation_id"],),
        )
    account        = get_account(acc_row["account_id"]) if acc_row else {}
    property_name  = account.get("property_name", "Property")
    business_phone = account.get("business_phone", "")
    currency       = account.get("currency", "UGX")

    receipt_number = _next_receipt_number()
    filename       = f"{receipt_number}.pdf"
    file_path      = os.path.join(RECEIPTS_DIR, filename)
    download_name  = f"{_safe_filename(display_name)}_{receipt_number}.pdf" if display_name else filename

    c = canvas.Canvas(file_path, pagesize=A5)
    width, height = A5
    y = height - 20 * mm

    c.setFont("Helvetica-Bold", 16)
    c.drawString(15 * mm, y, property_name)
    y -= 7 * mm
    c.setFont("Helvetica", 9)
    if business_phone:
        c.drawString(15 * mm, y, f"Tel: {business_phone}")
        y -= 6 * mm
    c.setStrokeColor(colors.grey)
    c.line(15 * mm, y, width - 15 * mm, y)
    y -= 10 * mm

    c.setFont("Helvetica-Bold", 13)
    c.drawString(15 * mm, y, "PAYMENT RECEIPT")
    c.setFont("Helvetica", 9)
    c.drawRightString(width - 15 * mm, y, receipt_number)
    y -= 10 * mm

    c.setFont("Helvetica", 10)
    rows = [
        ("Date",         payment["payment_date"]),
        ("Guest",        payment["full_name"]),
        ("Booking Ref",  payment["booking_ref"]),
        ("Unit",         f"{payment['unit_type']} — {payment['unit_number']}"),
        ("Payment type", payment["payment_type"].replace("_", " ").title()),
        ("Method",       payment["method"].replace("_", " ").title()),
    ]
    if payment.get("momo_reference"):
        rows.append(("Mobile Money Ref", payment["momo_reference"]))
    if payment.get("momo_provider"):
        rows.append(("Provider", payment["momo_provider"]))

    for label, value in rows:
        c.setFont("Helvetica-Bold", 10)
        c.drawString(15 * mm, y, f"{label}:")
        c.setFont("Helvetica", 10)
        c.drawString(65 * mm, y, str(value))
        y -= 7 * mm

    y -= 5 * mm
    c.line(15 * mm, y, width - 15 * mm, y)
    y -= 10 * mm

    c.setFont("Helvetica-Bold", 12)
    c.drawString(15 * mm, y, "Amount Paid:")
    c.drawRightString(width - 15 * mm, y, f"{currency} {payment['amount']:,.0f}")
    y -= 15 * mm

    if payment.get("note"):
        c.setFont("Helvetica-Oblique", 9)
        c.drawString(15 * mm, y, f"Note: {payment['note']}")

    c.setFont("Helvetica", 8)
    c.setFillColor(colors.grey)
    c.drawString(15 * mm, 15 * mm, "Generated by GuesthousePro — Smart Property & Guest Management")
    c.showPage()
    c.save()

    with get_conn() as conn:
        execute(conn,
            "INSERT INTO receipts (payment_id, receipt_number, file_path, download_name) "
            "VALUES (%s,%s,%s,%s)",
            (payment_id, receipt_number, file_path, download_name),
        )

    return {"receipt_number": receipt_number, "file_path": file_path, "download_name": download_name}


def get_receipt_for_payment(payment_id):
    with get_conn() as conn:
        return fetchone(conn, "SELECT * FROM receipts WHERE payment_id=%s", (payment_id,))
